#!/usr/bin/env python3
"""Generate CivicDesk's 5-stripe service-desk mark in the AAA Civic Horizon palette.

    python3 scripts/make_mark.py          # write templates/brand-mark.svg and static/favicon.svg
    python3 scripts/make_mark.py --check  # exit 1 if generated files are out of date

Palette (on #111827 slate ink):
  Stripe 1 & 5: #1D70B8 (sky)        3.43:1 non-text contrast on #111827
  Stripe 2 & 4: #C85A70 (muted rose) 4.35:1 non-text contrast on #111827
  Stripe 3:     #FFFFFF (paper)     17.74:1 non-text contrast on #111827 (wider central service counter)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# (x, y, width, height, role, hex_color)
STRIPES = [
    (7, 7.0, 26, 3.6, "sky", "#1D70B8"),
    (7, 12.6, 26, 3.6, "rose", "#C85A70"),
    (5, 18.2, 30, 3.6, "paper", "#FFFFFF"),
    (7, 23.8, 26, 3.6, "rose", "#C85A70"),
    (7, 29.4, 26, 3.6, "sky", "#1D70B8"),
]


def header_svg() -> str:
    bars = "".join(
        f'<rect x="{x}" y="{y:g}" width="{w}" height="{h:g}" rx="1.8" class="mark-{role}"/>'
        for x, y, w, h, role, _ in STRIPES
    )
    return (
        "{# Generated by scripts/make_mark.py. Edit that script, not this file. #}\n"
        '<svg class="brand-mark" aria-hidden="true" focusable="false" viewBox="0 0 40 40" width="40" height="40">'
        '<rect x="0" y="0" width="40" height="40" rx="8" class="mark-bg"/>'
        f"{bars}</svg>\n"
    )


def icon_svg() -> str:
    bars = "".join(
        f'<rect x="{x}" y="{y:g}" width="{w}" height="{h:g}" rx="1.8" fill="{color}"/>'
        for x, y, w, h, _, color in STRIPES
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40">'
        "<!-- CivicDesk 5-stripe service-desk mark. Generated by scripts/make_mark.py. -->"
        '<rect x="0" y="0" width="40" height="40" rx="8" fill="#111827"/>'
        f"{bars}</svg>\n"
    )


def main() -> int:
    targets = {
        ROOT / "templates" / "brand-mark.svg": header_svg(),
        ROOT / "static" / "favicon.svg": icon_svg(),
    }
    stale = [p for p, text in targets.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in sys.argv:
        for p in stale:
            print(f"Out of date: {p.relative_to(ROOT)}. Run python3 scripts/make_mark.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"Wrote {p.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
